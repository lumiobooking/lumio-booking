/**
 * What Google's Actions Center asks before it evaluates a partner: the Google
 * Business Profiles and landing pages of at least 25 merchants whose booking
 * link comes from our system, and how many merchants use it.
 *
 * Read straight off the agency's Google board — only salons whose profile
 * carries the Lumio booking link (set by the Place Actions API, state
 * "linked") and whose Maps link is known count. Nothing is invented: a salon
 * that is not linked is listed as the next one to fix, never as proof.
 */

export interface ProofRow {
  id: string; name: string; slug: string; status: 'ready' | 'fix' | 'off';
  mapsUrl: string | null; bookingLink?: { state: string; uri: string | null } | null;
}

export const GOOGLE_MINIMUM = 25;

export interface Proof {
  merchants: { name: string; maps: string; page: string }[];
  /** Merchants using Lumio for bookings: active salons that are not switched off (demo, restaurant, real estate). */
  using: number;
  /** Salons that could be linked next: ready but not linked yet, then those to fix. */
  next: { name: string; why: string }[];
}

export function buildProof(rows: ProofRow[]): Proof {
  const merchants = rows
    .filter((r) => r.status !== 'off' && r.bookingLink?.state === 'linked' && r.bookingLink.uri && r.mapsUrl)
    .map((r) => ({ name: r.name.trim(), maps: r.mapsUrl as string, page: r.bookingLink!.uri as string }))
    .sort((a, b) => a.name.localeCompare(b.name));
  const done = new Set(merchants.map((m) => m.name));
  const next = rows
    .filter((r) => r.status !== 'off' && !done.has(r.name.trim()))
    .map((r) => ({
      name: r.name.trim(),
      why: r.status === 'fix' ? 'cần sửa dữ liệu (xem bảng)'
        : !r.mapsUrl ? 'chưa có link Maps — nối Google / bấm “đọc lại”'
          : r.bookingLink?.state === 'error' ? 'lỗi gắn link — xem lý do'
            : 'sẵn sàng — bấm “🔗 Gắn link”',
      rank: r.status === 'ready' ? 0 : 1,
    }))
    .sort((a, b) => a.rank - b.rank || a.name.localeCompare(b.name))
    .map(({ name, why }) => ({ name, why }));
  return { merchants, using: rows.filter((r) => r.status !== 'off').length, next };
}

/** The reply to the Actions Center team, in English, with the list filled in. */
export function proofEmail(p: Proof, contactName = 'Utkan'): string {
  const list = p.merchants.map((m, i) => `${i + 1}. ${m.name}\n   Google Business Profile: ${m.maps}\n   Landing page: ${m.page}`).join('\n\n');
  return [
    `Hi ${contactName},`,
    '',
    'Thank you for the quick reply and for considering Lumio Booking for the Reserve with Google program.',
    '',
    `1) Merchants using links provided by our system (${p.merchants.length})`,
    'Each merchant below has the booking link generated by Lumio Booking set as the preferred appointment link on its own Google Business Profile (through the Business Profile Place Actions API). The link opens the merchant\'s booking page on our platform, which lists its services, durations, prices, opening hours and cancellation policy.',
    '',
    list,
    '',
    `2) Total merchants currently using our reservation system: ${p.using}`,
    '',
    'Please let me know if you need anything else, such as test access or sample feeds.',
    '',
    'Best regards,',
    'Lumio Agency LLC — Lumio Booking',
    'partners@lumiobooking.com · +1 (512) 886-8189',
  ].join('\n');
}

/** The same list as a spreadsheet (CSV, quoted). */
export function proofCsv(p: Proof): string {
  const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
  return ['#,Merchant,Google Business Profile,Landing page', ...p.merchants.map((m, i) => [String(i + 1), q(m.name), q(m.maps), q(m.page)].join(','))].join('\n') + '\n';
}
